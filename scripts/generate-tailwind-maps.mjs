import fs from "fs";
import path from "path";

const BREAKPOINTS = ["sm", "md", "lg", "xl", "2xl"];

const CONFIG = {
  BUTTON_SIZE_MAP: {
    xs: "btn-xs",
    sm: "btn-sm",
    md: "btn-md",
    lg: "btn-lg",
    xl: "btn-xl",
  },

  BUTTON_COLOR_MAP: {
    neutral: "btn-neutral",
    primary: "btn-primary",
    secondary: "btn-secondary",
    accent: "btn-accent",
    info: "btn-info",
    success: "btn-success",
    warning: "btn-warning",
    error: "btn-error",
  },

  BUTTON_VARIANT_MAP: {
    soft: "btn-soft",
    outline: "btn-outline",
    dash: "btn-dash",
    neutral: "btn-neutral",
    active: "btn-active",
    ghost: "btn-ghost",
    link: "btn-link",
  },

  BUTTON_SHAPE_MAP: {
    circle: "btn-circle",
    square: "btn-square",
  },

  BUTTON_DISPLAY_MAP: {
    wide: "btn-wide",
    block: "btn-block",
  },
};

function generateMapContents() {
  let output = `// Automatically generated by scripts/generate-tailwind-maps.mjs\n`;
  output += `// DO NOT EDIT MANUALLY\n\n`;

  for (const [mapName, values] of Object.entries(CONFIG)) {
    output += `export const ${mapName} = {\n`;

    for (const [key, className] of Object.entries(values)) {
      output += `  "${key}": {\n`;
      output += `    ['base']: "${className}",\n`;
      for (const bp of BREAKPOINTS) {
        output += `    ['${bp}']: "${bp}:${className}",\n`;
      }
      output += `  },\n`;
    }

    output += `} as const;\n\n`;
  }

  return output;
}

const outputPath = path.resolve("scripts/generated-tailwind-maps.ts");
fs.writeFileSync(outputPath, generateMapContents());
console.log(`✅ Tailwind maps generated at: ${outputPath}`);
